-- ====================================================================
-- LAKEHOUSE DATABASE INITIALIZATION (Medallion Architecture)
-- Schemas: BRONZE (Raw) -> SILVER (Cleaned) -> GOLD (Analytics / BI)
-- ====================================================================

-- 1. Buat Schema Medallion
CREATE SCHEMA IF NOT EXISTS bronze;
CREATE SCHEMA IF NOT EXISTS silver;
CREATE SCHEMA IF NOT EXISTS gold;

-- ====================================================================
-- LAYER 1: BRONZE (DATA MENTAH / RAW DATA)
-- Prinsip: Purely raw as-is from scraper, no alteration to content.
-- Idempotency: url / urlhash UNIQUE untuk mencegah duplikasi data mentah.
-- ====================================================================
DROP TABLE IF EXISTS bronze.articles CASCADE;

CREATE TABLE bronze.articles (
    id BIGSERIAL PRIMARY KEY,
    urlhash VARCHAR(64) UNIQUE NOT NULL,      -- Hash MD5 / SHA256 dari URL
    url TEXT UNIQUE NOT NULL,                  -- URL lengkap artikel
    id_url VARCHAR(50),                        -- ID unik artikel dari URL (misal: '603139')
    title TEXT,                                -- Judul mentah
    kategori VARCHAR(100),                     -- Kategori mentah
    published_time TEXT,                       -- Tanggal mentah berbentuk string (misal: "19 November 2026, 09:05 |")
    content TEXT,                              -- Isi artikel mentah
    tim_redaksi JSONB DEFAULT '[]'::jsonb,     -- Array of object: [{"href": "...", "text": "...", "bagian": "..."}]
    tags JSONB DEFAULT '[]'::jsonb,            -- Array of object: [{"href": "...", "text": "..."}]
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP -- Waktu scraping
);

-- Index untuk performa pencarian deduplikasi di bronze
CREATE INDEX IF NOT EXISTS idx_bronze_url ON bronze.articles(url);
CREATE INDEX IF NOT EXISTS idx_bronze_urlhash ON bronze.articles(urlhash);
CREATE INDEX IF NOT EXISTS idx_bronze_id_url ON bronze.articles(id_url);


-- ====================================================================
-- LAYER 2: SILVER (DATA BERSIH / TRANSFORMED & VALIDATED)
-- Prinsip: Bersih, null handled, tipe data sesuai (timestamp, array),
--          isi konten normal (tidak ada tag HTML liar/whitespace ganda).
-- ====================================================================
DROP TABLE IF EXISTS silver.articles CASCADE;

CREATE TABLE silver.articles (
    id BIGSERIAL PRIMARY KEY,
    bronze_id BIGINT REFERENCES bronze.articles(id) ON DELETE SET NULL, -- Lineage tracking ke data mentah
    url TEXT UNIQUE NOT NULL,
    id_url VARCHAR(50),
    title TEXT NOT NULL,
    kategori VARCHAR(100) NOT NULL,
    published_date TIMESTAMP WITH TIME ZONE NOT NULL, -- Format datetime standar ISO
    content TEXT NOT NULL,                            -- Teks bersih hasil preprocessing
    author VARCHAR(150),                              -- Reporter / Penulis utama yang sudah diekstrak
    editor VARCHAR(150),                              -- Editor yang sudah diekstrak
    tim_redaksi JSONB DEFAULT '[]'::jsonb,            -- Array of object bersih: [{"text": "...", "bagian": "..."}] (tanpa href)
    tags JSONB DEFAULT '[]'::jsonb,                   -- Array teks string bersih: ["ijazah", "dpr"] (tanpa href)
    word_count INTEGER,                               -- Total kata pada artikel
    char_count INTEGER,                               -- Total karakter artikel
    processed_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_silver_kategori ON silver.articles(kategori);
CREATE INDEX IF NOT EXISTS idx_silver_published_date ON silver.articles(published_date);


-- ====================================================================
-- LAYER 3: GOLD (DATA WAREHOUSE)
-- Star Schema tanpa Bridge Table.
-- Grain fact_article: satu baris untuk satu artikel.
-- ====================================================================

CREATE TABLE IF NOT EXISTS gold.dim_category (
    category_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_gold_dim_category_name_ci
    ON gold.dim_category (LOWER(BTRIM(category_name)));

INSERT INTO gold.dim_category (category_name)
VALUES ('Tidak Dikategorikan')
ON CONFLICT DO NOTHING;


CREATE TABLE IF NOT EXISTS gold.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day_of_month SMALLINT NOT NULL,
    day_of_week SMALLINT NOT NULL,
    day_name VARCHAR(20) NOT NULL,
    week_of_year SMALLINT NOT NULL,
    month_number SMALLINT NOT NULL,
    month_name VARCHAR(20) NOT NULL,
    quarter_number SMALLINT NOT NULL,
    year_number SMALLINT NOT NULL
);


CREATE TABLE IF NOT EXISTS gold.dim_reporter (
    reporter_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_gold_dim_reporter_name_ci
    ON gold.dim_reporter (LOWER(BTRIM(reporter_name)));

INSERT INTO gold.dim_reporter (reporter_name)
VALUES ('Tidak Diketahui')
ON CONFLICT DO NOTHING;


CREATE TABLE IF NOT EXISTS gold.dim_editor (
    editor_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    editor_name VARCHAR(150) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_gold_dim_editor_name_ci
    ON gold.dim_editor (LOWER(BTRIM(editor_name)));

INSERT INTO gold.dim_editor (editor_name)
VALUES ('Tidak Diketahui')
ON CONFLICT DO NOTHING;


CREATE TABLE IF NOT EXISTS gold.fact_article (
    article_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    silver_article_id BIGINT NOT NULL,
    article_url TEXT NOT NULL,
    category_key BIGINT NOT NULL,
    article_count INTEGER NOT NULL DEFAULT 1 CHECK (article_count = 1),
    loaded_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    title TEXT,
    published_date TIMESTAMP WITH TIME ZONE,
    published_local_datetime TIMESTAMP WITHOUT TIME ZONE,
    date_key INTEGER,
    reporter_key BIGINT,
    editor_key BIGINT,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    word_count INTEGER,
    char_count INTEGER,

    CONSTRAINT fk_fact_article_silver
        FOREIGN KEY (silver_article_id)
        REFERENCES silver.articles(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_fact_article_category
        FOREIGN KEY (category_key)
        REFERENCES gold.dim_category(category_key),

    CONSTRAINT uq_fact_article_silver_id UNIQUE (silver_article_id),
    CONSTRAINT uq_fact_article_url UNIQUE (article_url)
);

ALTER TABLE gold.fact_article
    ADD COLUMN IF NOT EXISTS title TEXT,
    ADD COLUMN IF NOT EXISTS published_date TIMESTAMP WITH TIME ZONE,
    ADD COLUMN IF NOT EXISTS published_local_datetime TIMESTAMP WITHOUT TIME ZONE,
    ADD COLUMN IF NOT EXISTS date_key INTEGER,
    ADD COLUMN IF NOT EXISTS reporter_key BIGINT,
    ADD COLUMN IF NOT EXISTS editor_key BIGINT,
    ADD COLUMN IF NOT EXISTS tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    ADD COLUMN IF NOT EXISTS word_count INTEGER,
    ADD COLUMN IF NOT EXISTS char_count INTEGER;

CREATE INDEX IF NOT EXISTS idx_gold_fact_article_category_key
    ON gold.fact_article (category_key);

CREATE INDEX IF NOT EXISTS idx_gold_fact_article_date_key
    ON gold.fact_article (date_key);

CREATE INDEX IF NOT EXISTS idx_gold_fact_article_reporter_key
    ON gold.fact_article (reporter_key);

CREATE INDEX IF NOT EXISTS idx_gold_fact_article_editor_key
    ON gold.fact_article (editor_key);


DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_fact_article_silver'
          AND conrelid = 'gold.fact_article'::regclass
    ) THEN
        ALTER TABLE gold.fact_article
        ADD CONSTRAINT fk_fact_article_silver
        FOREIGN KEY (silver_article_id)
        REFERENCES silver.articles(id)
        ON DELETE CASCADE;
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_fact_article_category'
          AND conrelid = 'gold.fact_article'::regclass
    ) THEN
        ALTER TABLE gold.fact_article
        ADD CONSTRAINT fk_fact_article_category
        FOREIGN KEY (category_key)
        REFERENCES gold.dim_category(category_key);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_fact_article_date'
          AND conrelid = 'gold.fact_article'::regclass
    ) THEN
        ALTER TABLE gold.fact_article
        ADD CONSTRAINT fk_fact_article_date
        FOREIGN KEY (date_key)
        REFERENCES gold.dim_date(date_key);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_fact_article_reporter'
          AND conrelid = 'gold.fact_article'::regclass
    ) THEN
        ALTER TABLE gold.fact_article
        ADD CONSTRAINT fk_fact_article_reporter
        FOREIGN KEY (reporter_key)
        REFERENCES gold.dim_reporter(reporter_key);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_fact_article_editor'
          AND conrelid = 'gold.fact_article'::regclass
    ) THEN
        ALTER TABLE gold.fact_article
        ADD CONSTRAINT fk_fact_article_editor
        FOREIGN KEY (editor_key)
        REFERENCES gold.dim_editor(editor_key);
    END IF;
END $$;


CREATE TABLE IF NOT EXISTS gold.daily_article_metrics (
    id BIGSERIAL PRIMARY KEY,
    metric_date DATE NOT NULL,
    kategori VARCHAR(100) NOT NULL,
    total_articles INTEGER DEFAULT 0,
    avg_words_per_article NUMERIC(10, 2) DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_date_kategori UNIQUE (metric_date, kategori)
);


CREATE TABLE IF NOT EXISTS gold.editor_team_productivity (
    id BIGSERIAL PRIMARY KEY,
    member_name VARCHAR(150) NOT NULL,
    role VARCHAR(50) NOT NULL,
    total_articles INTEGER DEFAULT 0,
    first_article_date DATE,
    latest_article_date DATE,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_member_role UNIQUE (member_name, role)
);


CREATE OR REPLACE VIEW gold.v_recent_articles_dashboard AS
SELECT
    id,
    title,
    kategori,
    author,
    editor,
    published_date,
    word_count,
    url
FROM silver.articles
ORDER BY published_date DESC;
