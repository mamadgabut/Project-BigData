import logging

from db_connection import get_connection


logger = logging.getLogger(__name__)

DEFAULT_CATEGORY = "Tidak Dikategorikan"
UNKNOWN_MEMBER = "Tidak Diketahui"


def _open_connection():
    connection = get_connection()
    if connection is None:
        raise ConnectionError(
            "Koneksi PostgreSQL gagal. Periksa container Docker dan konfigurasi .env."
        )
    return connection


def validate_silver_source():
    connection = _open_connection()

    try:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    COUNT(*) AS total_rows,
                    COUNT(*) FILTER (
                        WHERE url IS NULL OR BTRIM(url) = ''
                    ) AS invalid_urls,
                    COUNT(*) FILTER (
                        WHERE published_date IS NULL
                    ) AS invalid_published_dates,
                    COUNT(*) FILTER (
                        WHERE kategori IS NULL OR BTRIM(kategori) = ''
                    ) AS empty_categories,
                    COUNT(*) FILTER (
                        WHERE author IS NULL OR BTRIM(author) = ''
                    ) AS missing_reporters,
                    COUNT(*) FILTER (
                        WHERE editor IS NULL OR BTRIM(editor) = ''
                    ) AS missing_editors
                FROM silver.articles;
                """
            )
            (
                total_rows,
                invalid_urls,
                invalid_published_dates,
                empty_categories,
                missing_reporters,
                missing_editors,
            ) = cursor.fetchone()

        if invalid_urls > 0:
            raise ValueError(
                f"Ditemukan {invalid_urls} artikel Silver dengan URL kosong."
            )

        if invalid_published_dates > 0:
            raise ValueError(
                f"Ditemukan {invalid_published_dates} artikel Silver tanpa tanggal publikasi."
            )

        result = {
            "total_silver": total_rows,
            "invalid_urls": invalid_urls,
            "invalid_published_dates": invalid_published_dates,
            "empty_categories": empty_categories,
            "missing_reporters": missing_reporters,
            "missing_editors": missing_editors,
        }

        logger.info("Validasi Silver selesai: %s", result)
        return result

    finally:
        connection.close()


