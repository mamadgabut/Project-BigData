def load_fact_article():
    connection = _open_connection()

    try:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO gold.fact_article (
                    silver_article_id,
                    article_url,
                    title,
                    published_date,
                    published_local_datetime,
                    date_key,
                    category_key,
                    reporter_key,
                    editor_key,
                    tags,
                    word_count,
                    char_count,
                    article_count
                )
                SELECT
                    s.id,
                    s.url,
                    s.title,
                    s.published_date,
                    s.published_date AT TIME ZONE current_setting('TimeZone'),
                    TO_CHAR(
                        (
                            s.published_date AT TIME ZONE current_setting('TimeZone')
                        )::DATE,
                        'YYYYMMDD'
                    )::INTEGER,
                    dc.category_key,
                    dr.reporter_key,
                    de.editor_key,
                    CASE
                        WHEN jsonb_typeof(s.tags) = 'array' THEN s.tags
                        ELSE '[]'::jsonb
                    END,
                    s.word_count,
                    s.char_count,
                    1
                FROM silver.articles AS s
                JOIN gold.dim_category AS dc
                    ON LOWER(BTRIM(dc.category_name)) =
                       LOWER(
                           COALESCE(
                               NULLIF(BTRIM(s.kategori), ''),
                               %s
                           )
                       )
                JOIN gold.dim_reporter AS dr
                    ON LOWER(BTRIM(dr.reporter_name)) =
                       LOWER(COALESCE(NULLIF(BTRIM(s.author), ''), %s))
                JOIN gold.dim_editor AS de
                    ON LOWER(BTRIM(de.editor_name)) =
                       LOWER(COALESCE(NULLIF(BTRIM(s.editor), ''), %s))
                ON CONFLICT (silver_article_id)
                DO UPDATE SET
                    article_url = EXCLUDED.article_url,
                    title = EXCLUDED.title,
                    published_date = EXCLUDED.published_date,
                    published_local_datetime = EXCLUDED.published_local_datetime,
                    date_key = EXCLUDED.date_key,
                    category_key = EXCLUDED.category_key,
                    reporter_key = EXCLUDED.reporter_key,
                    editor_key = EXCLUDED.editor_key,
                    tags = EXCLUDED.tags,
                    word_count = EXCLUDED.word_count,
                    char_count = EXCLUDED.char_count,
                    article_count = 1,
                    loaded_at = CURRENT_TIMESTAMP;
                """,
                (DEFAULT_CATEGORY, UNKNOWN_MEMBER, UNKNOWN_MEMBER),
            )
            affected_count = cursor.rowcount

        connection.commit()
        logger.info("Artikel yang dimasukkan/diperbarui di fact_article: %s.", affected_count)
        return affected_count

    except Exception:
        connection.rollback()
        logger.exception("Gagal memuat fact_article.")
        raise

    finally:
        connection.close()


def validate_gold():
    connection = _open_connection()

    try:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    (SELECT COUNT(*) FROM silver.articles) AS total_silver,
                    (SELECT COUNT(*) FROM gold.fact_article) AS total_fact,
                    (
                        SELECT COUNT(*)
                        FROM silver.articles AS s
                        LEFT JOIN gold.fact_article AS f
                            ON f.silver_article_id = s.id
                        WHERE f.article_key IS NULL
                    ) AS missing_fact,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article AS f
                        LEFT JOIN gold.dim_category AS d
                            ON d.category_key = f.category_key
                        WHERE d.category_key IS NULL
                    ) AS invalid_category_reference,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article AS f
                        LEFT JOIN gold.dim_date AS d
                            ON d.date_key = f.date_key
                        WHERE d.date_key IS NULL
                    ) AS invalid_date_reference,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article AS f
                        LEFT JOIN gold.dim_reporter AS r
                            ON r.reporter_key = f.reporter_key
                        WHERE r.reporter_key IS NULL
                    ) AS invalid_reporter_reference,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article AS f
                        LEFT JOIN gold.dim_editor AS e
                            ON e.editor_key = f.editor_key
                        WHERE e.editor_key IS NULL
                    ) AS invalid_editor_reference,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article AS f
                        LEFT JOIN silver.articles AS s
                            ON s.id = f.silver_article_id
                        WHERE s.id IS NULL
                    ) AS orphan_fact,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article
                        WHERE tags IS NULL OR jsonb_typeof(tags) <> 'array'
                    ) AS invalid_tags_format,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article
                        WHERE article_count <> 1
                    ) AS invalid_article_count,
                    (
                        SELECT COUNT(*)
                        FROM gold.fact_article
                        WHERE published_local_datetime IS NULL
                    ) AS missing_local_datetime;
                """
            )
            columns = [description[0] for description in cursor.description]
            values = cursor.fetchone()
            result = dict(zip(columns, values))

        checks_to_zero = [
            "missing_fact",
            "invalid_category_reference",
            "invalid_date_reference",
            "invalid_reporter_reference",
            "invalid_editor_reference",
            "orphan_fact",
            "invalid_tags_format",
            "invalid_article_count",
            "missing_local_datetime",
        ]

        logger.info("Hasil validasi Gold: %s", result)

        if result["total_silver"] != result["total_fact"] or any(
            result[key] > 0 for key in checks_to_zero
        ):
            raise ValueError(
                "Validasi Gold gagal. Periksa jumlah artikel dan relasi dimensi-fakta. "
                f"Detail: {result}"
            )

        logger.info("Validasi Gold berhasil.")
        return result

    finally:
        connection.close()


def create_analytics_views():
    view_statements = [
        (
            "v_article_distribution_by_category",
            """
            CREATE OR REPLACE VIEW gold.v_article_distribution_by_category AS
            SELECT
                d.category_key,
                d.category_name,
                SUM(f.article_count)::BIGINT AS total_articles,
                ROUND(
                    SUM(f.article_count)::NUMERIC * 100
                    / NULLIF(SUM(SUM(f.article_count)) OVER (), 0),
                    2
                ) AS percentage
            FROM gold.fact_article AS f
            JOIN gold.dim_category AS d
                ON d.category_key = f.category_key
            GROUP BY d.category_key, d.category_name;
            """,
        ),
        (
            "v_article_publication_trend",
            """
            CREATE OR REPLACE VIEW gold.v_article_publication_trend AS
            WITH article_dates AS (
                SELECT
                    f.article_key,
                    d.full_date AS publication_date
                FROM gold.fact_article AS f
                JOIN gold.dim_date AS d
                    ON d.date_key = f.date_key
            )
            SELECT
                'Harian'::VARCHAR(10) AS period_type,
                publication_date AS period_start,
                COUNT(*)::BIGINT AS total_articles
            FROM article_dates
            GROUP BY publication_date

            UNION ALL

            SELECT
                'Mingguan'::VARCHAR(10) AS period_type,
                DATE_TRUNC('week', publication_date::TIMESTAMP)::DATE AS period_start,
                COUNT(*)::BIGINT AS total_articles
            FROM article_dates
            GROUP BY DATE_TRUNC('week', publication_date::TIMESTAMP)::DATE

            UNION ALL

            SELECT
                'Bulanan'::VARCHAR(10) AS period_type,
                DATE_TRUNC('month', publication_date::TIMESTAMP)::DATE AS period_start,
                COUNT(*)::BIGINT AS total_articles
            FROM article_dates
            GROUP BY DATE_TRUNC('month', publication_date::TIMESTAMP)::DATE;
            """,
        ),
        (
            "v_article_publication_by_hour",
            """
            CREATE OR REPLACE VIEW gold.v_article_publication_by_hour AS
            SELECT
                EXTRACT(HOUR FROM published_local_datetime)::INTEGER
                    AS publication_hour,
                COUNT(*)::BIGINT AS total_articles
            FROM gold.fact_article
            WHERE published_local_datetime IS NOT NULL
            GROUP BY EXTRACT(HOUR FROM published_local_datetime)::INTEGER;
            """,
        ),
        (
            "v_article_publication_by_day",
            """
            CREATE OR REPLACE VIEW gold.v_article_publication_by_day AS
            SELECT
                d.day_of_week,
                d.day_name,
                COUNT(*)::BIGINT AS total_articles
            FROM gold.fact_article AS f
            JOIN gold.dim_date AS d
                ON d.date_key = f.date_key
            GROUP BY d.day_of_week, d.day_name;
            """,
        ),
        (
            "v_reporter_productivity",
            """
            CREATE OR REPLACE VIEW gold.v_reporter_productivity AS
            SELECT
                r.reporter_key,
                r.reporter_name,
                COUNT(f.article_key)::BIGINT AS total_articles,
                MIN(d.full_date) AS first_article_date,
                MAX(d.full_date) AS latest_article_date,
                DENSE_RANK() OVER (
                    ORDER BY COUNT(f.article_key) DESC
                ) AS ranking
            FROM gold.dim_reporter AS r
            LEFT JOIN gold.fact_article AS f
                ON f.reporter_key = r.reporter_key
            LEFT JOIN gold.dim_date AS d
                ON d.date_key = f.date_key
            WHERE r.reporter_name <> 'Tidak Diketahui'
            GROUP BY r.reporter_key, r.reporter_name;
            """,
        ),
        (
            "v_editor_productivity",
            """
            CREATE OR REPLACE VIEW gold.v_editor_productivity AS
            SELECT
                e.editor_key,
                e.editor_name,
                COUNT(f.article_key)::BIGINT AS total_articles,
                MIN(d.full_date) AS first_article_date,
                MAX(d.full_date) AS latest_article_date,
                DENSE_RANK() OVER (
                    ORDER BY COUNT(f.article_key) DESC
                ) AS ranking
            FROM gold.dim_editor AS e
            LEFT JOIN gold.fact_article AS f
                ON f.editor_key = e.editor_key
            LEFT JOIN gold.dim_date AS d
                ON d.date_key = f.date_key
            WHERE e.editor_name <> 'Tidak Diketahui'
            GROUP BY e.editor_key, e.editor_name;
            """,
        ),
        (
            "v_daily_tag_trend",
            """
            CREATE OR REPLACE VIEW gold.v_daily_tag_trend AS
            SELECT
                f.published_local_datetime::DATE AS publication_date,
                LOWER(BTRIM(tag_item.tag_name)) AS tag_name,
                COUNT(DISTINCT f.article_key)::BIGINT AS total_articles
            FROM gold.fact_article AS f
            CROSS JOIN LATERAL jsonb_array_elements_text(
                CASE
                    WHEN jsonb_typeof(f.tags) = 'array' THEN f.tags
                    ELSE '[]'::jsonb
                END
            ) AS tag_item(tag_name)
            WHERE f.published_local_datetime IS NOT NULL
              AND BTRIM(tag_item.tag_name) <> ''
            GROUP BY
                f.published_local_datetime::DATE,
                LOWER(BTRIM(tag_item.tag_name));
            """,
        ),
        (
            "v_article_length_by_category",
            """
            CREATE OR REPLACE VIEW gold.v_article_length_by_category AS
            SELECT
                d.category_key,
                d.category_name,
                COUNT(f.article_key)::BIGINT AS total_articles,
                ROUND(AVG(f.word_count)::NUMERIC, 2) AS avg_word_count,
                ROUND(AVG(f.char_count)::NUMERIC, 2) AS avg_char_count,
                MIN(f.word_count) AS min_word_count,
                MAX(f.word_count) AS max_word_count,
                MIN(f.char_count) AS min_char_count,
                MAX(f.char_count) AS max_char_count
            FROM gold.fact_article AS f
            JOIN gold.dim_category AS d
                ON d.category_key = f.category_key
            GROUP BY d.category_key, d.category_name;
            """,
        ),
        (
            "v_article_length_extremes",
            """
            CREATE OR REPLACE VIEW gold.v_article_length_extremes AS
            WITH ranked_articles AS (
                SELECT
                    article_key,
                    title,
                    article_url,
                    word_count,
                    char_count,
                    ROW_NUMBER() OVER (
                        ORDER BY word_count DESC, char_count DESC NULLS LAST, article_key
                    ) AS longest_rank,
                    ROW_NUMBER() OVER (
                        ORDER BY word_count ASC, char_count ASC NULLS LAST, article_key
                    ) AS shortest_rank
                FROM gold.fact_article
                WHERE word_count IS NOT NULL
            )
            SELECT
                'Terpanjang'::VARCHAR(20) AS article_length_type,
                title,
                article_url,
                word_count,
                char_count
            FROM ranked_articles
            WHERE longest_rank = 1

            UNION ALL

            SELECT
                'Terpendek'::VARCHAR(20) AS article_length_type,
                title,
                article_url,
                word_count,
                char_count
            FROM ranked_articles
            WHERE shortest_rank = 1;
            """,
        ),
    ]

    connection = _open_connection()

    try:
        with connection.cursor() as cursor:
            for view_name, statement in view_statements:
                cursor.execute(statement)
                logger.info("View Gold berhasil dibuat/diperbarui: %s.", view_name)

        connection.commit()
        return [view_name for view_name, _ in view_statements]

    except Exception:
        connection.rollback()
        logger.exception("Gagal membuat view analitik Gold.")
        raise

    finally:
        connection.close()


